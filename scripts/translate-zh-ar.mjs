const LANGS = new Set(['ru', 'en', 'uz', 'zh', 'ar', 'uk']);
function isLocalized(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
  const keys = Object.keys(value);
  return keys.length > 0 && keys.every((k) => LANGS.has(k));
}

let filled = 0;

function walk(value) {
  if (Array.isArray(value)) { value.forEach(walk); return; }
  if (!value || typeof value !== 'object') return;

  if (isLocalized(value)) {
    const ru = value.ru;
    if (typeof ru === 'string') {
      if (!value.zh && ZH[ru]) { value.zh = ZH[ru]; filled += 1; }
      if (!value.ar && AR[ru]) { value.ar = AR[ru]; filled += 1; }
    }
    return;
  }
  Object.values(value).forEach(walk);
}

const content = await file.read();
for (const [key, value] of Object.entries(content)) {
  if (key === 'UI_TEXT' || key === 'LANGUAGE_OPTIONS') continue;
  walk(value);
}
file.write(content);
