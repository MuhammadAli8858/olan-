export function localize(value, language) {
  if (value == null) return '';
  if (typeof value === 'string' || typeof value === 'number') return value;
  if (Array.isArray(value)) return value;
  // Порядок отката: нужный язык → английский → русский → первое непустое.
  // Английский раньше русского: для арабского и китайского читателя
  // латиница понятнее кириллицы.
  return value[language]
    ?? value.en
    ?? value.ru
    ?? Object.values(value).find((v) => v !== '' && v != null)
    ?? '';
}
