// Насколько часто встречается страна в ленте. Узбекистану вес больше:
// сайт узбекской компании, и лента должна выглядеть местной, а не
// подборкой иностранных машин.
const WEIGHTS = { UZ: 40, RU: 16, KZ: 14, KG: 12, TJ: 10, BY: 8 };

const BAG = COUNTRIES.flatMap((country) => Array(WEIGHTS[country.code] || 10).fill(country));

// Случайный номер: сначала выбирается страна, затем существующий регион,
// остальное собирается по формату этой страны.
export function randomPlate() {
  const country = pick(BAG);
  return country.make(pick(country.regions));
}
