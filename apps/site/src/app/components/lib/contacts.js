// Лёгкие проверки контактов.
//
// Живут отдельно от PhoneField намеренно: сам PhoneField тянет за собой
// базу правил телефонных номеров на сотню килобайт и подгружается лениво,
// а проверка адреса почты нужна сразу и весит три строки.

// Одна собака, точка в домене, никаких пробелов. Более строгая проверка
// отсекает живые адреса, а более мягкая пропускает мусор.
export function isEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(String(value || '').trim());
}
